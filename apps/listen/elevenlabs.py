"""Thin ElevenLabs API client for Listen's voice catalog and library search (apps/listen/elevenlabs.py).

Speech itself is generated by the node stream server (node/listen.coffee); Django only reads voice metadata.
"""

import requests
from django.conf import settings

from utils import log as logging

API_BASE = "https://api.elevenlabs.io"
TIMEOUT_SECONDS = 10
PLACEHOLDER_PREFIXES = ("sk_XXXX", "XXXX")


def api_key():
    key = getattr(settings, "ELEVENLABS_API_KEY", "") or ""
    if not key or key.startswith(PLACEHOLDER_PREFIXES):
        return None
    return key


def is_configured():
    return bool(api_key())


def _get(path, params=None):
    key = api_key()
    if not key:
        return None
    try:
        response = requests.get(
            f"{API_BASE}{path}", params=params, headers={"xi-api-key": key}, timeout=TIMEOUT_SECONDS
        )
    except requests.RequestException as e:
        logging.debug(f" ---> ~FRElevenLabs request failed: {path} {e}")
        return None
    if response.status_code != 200:
        logging.debug(f" ---> ~FRElevenLabs {path} returned {response.status_code}: {response.text[:200]}")
        return None
    return response.json()


def shared_voices(**params):
    """Search the public voice library. Voices that charge a surcharge or need live moderation are excluded."""
    query = {"include_custom_rates": "false", "include_live_moderated": "false"}
    query.update({key: value for key, value in params.items() if value not in (None, "", [])})
    return _get("/v1/shared-voices", query)


def account_voices():
    """Voices on the NewsBlur ElevenLabs account, which include the premade multilingual voices."""
    return _get("/v2/voices", {"page_size": 100})
